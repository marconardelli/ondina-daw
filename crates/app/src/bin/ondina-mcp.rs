//! `ondina-mcp`: console entry point for MCP clients that speak stdio.
//!
//! * `ondina-mcp`                 — bridge to the running Ondina app (http://127.0.0.1:3917/mcp)
//! * `ondina-mcp --url <url>`     — bridge to a custom endpoint
//! * `ondina-mcp --headless`      — run a private headless Ondina session over stdio
//!   (add `--audio` to also play sound through the default output device)

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let has = |f: &str| args.iter().any(|a| a == f);
    let value = |f: &str| {
        args.iter()
            .position(|a| a == f)
            .and_then(|i| args.get(i + 1))
            .cloned()
    };
    if has("--help") || has("-h") {
        eprintln!("ondina-mcp [--url http://127.0.0.1:3917/mcp] | --headless [--audio] [--project file.ondina]");
        return;
    }
    if has("--list-tools") {
        println!("# Ondina DAW — MCP tools\n\nGenerated by `ondina-mcp --list-tools`. Every tool maps 1:1 to an undoable command of the app.\n");
        for t in ondina_studio::mcp::tools() {
            let props = t.input_schema["properties"]
                .as_object()
                .map(|m| m.keys().cloned().collect::<Vec<_>>().join(", "))
                .unwrap_or_default();
            let params = if props.is_empty() {
                "none".to_string()
            } else {
                format!("`{props}`")
            };
            let ro = if t.read_only { " · read-only" } else { "" };
            println!(
                "### `{}`{}\n{}\n\nParameters: {}\n",
                t.name, ro, t.description, params
            );
        }
        return;
    }
    if has("--headless") {
        let session = ondina_studio::Session::shared(has("--audio"));
        if let Some(p) = value("--project") {
            let r = session.lock().execute(
                ondina_core::Command::OpenProject { path: p },
                ondina_studio::Source::Script,
            );
            if let Err(e) = r {
                eprintln!("[ondina-mcp] {e}");
            }
        }
        eprintln!("[ondina-mcp] headless session ready on stdio");
        ondina_studio::mcp::serve_stdio(session);
    } else {
        let url = value("--url").unwrap_or_else(|| "http://127.0.0.1:3917/mcp".into());
        eprintln!("[ondina-mcp] bridging stdio to {url}");
        ondina_studio::mcp::serve_bridge(&url);
    }
}
